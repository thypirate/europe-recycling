// Regenerates src/data/wasteTrade.ts from Eurostat's env_wasship dataset
// ("Transboundary shipments of notified waste by partner, hazardousness and
// waste management operations").
//
//   npx tsx scripts/fetch-waste-trade.ts            # latest year, top 40 flows
//   npx tsx scripts/fetch-waste-trade.ts --year 2023 --top 30
//
// Each arc is one exporter → partner flow as reported by the exporting country,
// hazardous + non-hazardous, in tonnes. Only flows where both ends are countries
// on the globe are kept, and the largest `--top` of those are written.

import { writeFileSync } from "node:fs";
import { recyclingData } from "../src/data/recycling.ts";

const DATASET = "env_wasship";
const API = `https://ec.europa.eu/eurostat/api/dissemination/statistics/1.0/data/${DATASET}`;
const BROWSER = `https://ec.europa.eu/eurostat/databrowser/view/${DATASET}/default/table?lang=en`;
const OUT = new URL("../src/data/wasteTrade.ts", import.meta.url);

// A flow is labelled recovery or disposal when that operation accounts for at
// least this share of its tonnage; anything in between is "mixed".
const DOMINANT_SHARE = 0.75;

// Countries that receive shipments but are not points on the globe.
const EXTRA_COORDS: Record<string, [number, number]> = { UK: [55.38, -3.44] };

const args = process.argv.slice(2);
const arg = (name: string) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 ? args[i + 1] : undefined;
};
const top = Number(arg("top") ?? 40);

const coords = new Map<string, [number, number]>([
  ...recyclingData.map((c) => [c.code, [c.lat, c.lng]] as [string, [number, number]]),
  ...Object.entries(EXTRA_COORDS),
]);

interface JsonStat {
  id: string[];
  size: number[];
  value: Record<string, number>;
  dimension: Record<string, { category: { index: Record<string, number> } }>;
}

const params = new URLSearchParams({ format: "JSON", lang: "EN", stk_flow: "EXP", hazard: "HAZ_NHAZ", unit: "T" });
for (const op of ["TRT", "RCV", "DSP"]) params.append("wst_oper", op);
const year = arg("year");
if (year) params.set("time", year);
else params.set("lastTimePeriod", "1");

const res = await fetch(`${API}?${params}`);
if (!res.ok) throw new Error(`Eurostat ${res.status}: ${await res.text()}`);
const data = (await res.json()) as JsonStat;

const cats = Object.fromEntries(
  data.id.map((k) => {
    const index = data.dimension[k].category.index;
    return [k, Object.keys(index).sort((a, b) => index[a] - index[b])];
  }),
);
const [refYear] = cats.time;
if (cats.time.length !== 1) throw new Error(`expected one year, got ${cats.time}`);

function value(sel: Record<string, string>): number {
  let pos = 0;
  data.id.forEach((k, i) => {
    const at = sel[k] ?? cats[k][0];
    pos = pos * data.size[i] + cats[k].indexOf(at);
  });
  return data.value[String(pos)] ?? 0;
}

const flows = [];
for (const geo of cats.geo) {
  for (const partner of cats.partner) {
    if (geo === partner || !coords.has(geo) || !coords.has(partner)) continue;
    const total = value({ geo, partner, wst_oper: "TRT" });
    if (!total) continue;
    const recovery = value({ geo, partner, wst_oper: "RCV" });
    const disposal = value({ geo, partner, wst_oper: "DSP" });
    const flowType =
      recovery / total >= DOMINANT_SHARE
        ? "recovery"
        : disposal / total >= DOMINANT_SHARE
          ? "disposal"
          : "mixed";
    flows.push({ geo, partner, total, recovery, disposal, flowType });
  }
}
flows.sort((a, b) => b.total - a.total);
const kept = flows.slice(0, top);

const COLORS = { recovery: "#00ff88cc", disposal: "#ff4444cc", mixed: "#ffaa00cc" };
const arcs = kept.map((f) => {
  const [startLat, startLng] = coords.get(f.geo)!;
  const [endLat, endLng] = coords.get(f.partner)!;
  return {
    startLat,
    startLng,
    endLat,
    endLng,
    color: COLORS[f.flowType as keyof typeof COLORS],
    label: `${f.geo} → ${f.partner}`,
    from: f.geo,
    to: f.partner,
    tonnes: f.total,
    recoveryTonnes: f.recovery,
    disposalTonnes: f.disposal,
    flowType: f.flowType,
  };
});

const source = {
  dataset: DATASET,
  title:
    "Transboundary shipments of notified waste by partner, hazardousness and waste management operations",
  url: BROWSER,
  year: Number(refYear),
  retrieved: new Date().toISOString().slice(0, 10),
  note: `Exports reported by the exporting country, hazardous and non-hazardous, in tonnes. Largest ${top} flows between countries on the globe. Recovery/disposal when that operation is ≥ ${DOMINANT_SHARE * 100}% of the flow, otherwise mixed.`,
};

const file = `// Generated by scripts/fetch-waste-trade.ts — do not edit by hand.
// Regenerate with: npx tsx scripts/fetch-waste-trade.ts

export interface GlobeArc {
  startLat: number;
  startLng: number;
  endLat: number;
  endLng: number;
  color: string;
  label: string;
  from: string;
  to: string;
  tonnes: number;
  recoveryTonnes: number;
  disposalTonnes: number;
  flowType: "recovery" | "disposal" | "mixed";
}

export const WasteTradeSource = ${JSON.stringify(source, null, 2)} as const;

export const WasteTradeArcs: GlobeArc[] = ${JSON.stringify(arcs, null, 2)};
`;

writeFileSync(OUT, file);
console.log(
  `wrote ${arcs.length} of ${flows.length} flows for ${refYear} (${kept.at(-1)?.total.toLocaleString()} t smallest kept)`,
);
